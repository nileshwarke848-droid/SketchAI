#!/usr/bin/env node
// Create a throwaway 345-class model so the two-model integration can be tested
// in a fresh checkout that has no trained model.
//
// This is a TEST FIXTURE. Its weights are random: it has never seen a drawing and
// its predictions are meaningless. It exists only so that
//
//   * the primary/fallback loading order can be exercised, and
//   * the 345-output path of the UI (top-10 over 345 labels) can be checked
//
// without waiting hours for a real training run. install-model-345.mjs refuses to
// install it into a build, and the file it writes is named so nobody mistakes it
// for a real classifier.
//
//   node scripts/make-fixture-model-345.mjs [output-dir]

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = path.resolve(process.argv[2] ?? path.join(ROOT, 'public', 'model-345'));

const tf = await import('@tensorflow/tfjs');
await tf.setBackend('cpu');
await tf.ready();

const model = tf.sequential({
  layers: [
    tf.layers.inputLayer({ inputShape: [28, 28, 1] }),
    tf.layers.flatten(),
    tf.layers.dense({ units: 345, activation: 'softmax' }),
  ],
});

let payload = null;
await model.save(
  tf.io.withSaveHandler(async (artifacts) => {
    payload = {
      spec: {
        format: artifacts.format,
        generatedBy: artifacts.generatedBy,
        convertedBy: artifacts.convertedBy,
        modelTopology: artifacts.modelTopology,
        weightsManifest: [{ paths: ['group1-shard1of1.bin'], weights: artifacts.weightSpecs }],
      },
      data: Buffer.from(artifacts.weightData),
    };
    return { modelArtifactsInfo: { dateSaved: new Date(), modelTopologyType: 'JSON' } };
  }),
);

fs.mkdirSync(OUTPUT, { recursive: true });
fs.writeFileSync(path.join(OUTPUT, 'model.json'), JSON.stringify(payload.spec));
fs.writeFileSync(path.join(OUTPUT, 'group1-shard1of1.bin'), payload.data);
fs.copyFileSync(path.join(ROOT, 'src', 'data', 'quickdraw-categories.txt'), path.join(OUTPUT, 'classes.txt'));
fs.writeFileSync(
  path.join(OUTPUT, 'manifest.json'),
  JSON.stringify(
    {
      name: 'SketchAI 345-class INTEGRATION TEST FIXTURE',
      is_self_test_only: true,
      note:
        'Random weights generated by scripts/make-fixture-model-345.mjs. Never ship this: it ' +
        'has not been trained and its predictions are meaningless.',
      categories: 345,
      output_classes: 345,
      parameters: model.countParams(),
    },
    null,
    2,
  ) + '\n',
);

console.log(`Wrote test fixture to ${path.relative(ROOT, OUTPUT) || OUTPUT}`);
console.log(`  345 outputs · ${model.countParams().toLocaleString()} parameters · ` +
  `${(payload.data.length / 1024 / 1024).toFixed(2)} MB of random weights`);
console.log('  install-model-345.mjs will refuse this folder; it is for tests only.');
